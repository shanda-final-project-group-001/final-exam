def weekday_of(date_str: str) -> str:
    return WEEKDAYS[datetime.strptime(date_str, "%Y-%m-%d").weekday()]


def build_enrollments() -> list[tuple[str, str, str, str]]:
    """确定性地生成 40 条报名记录，并保证 A005 满员。"""
    open_ids = [a[0] for a in ACTIVITIES if a[12] == "open"]
    capacities = {a[0]: a[7] for a in ACTIVITIES}  # 第 8 个字段为名额
    fixed = [("E1001", "S001", "A003"), ("E1002", "S002", "A005"), ("E1003", "S003", "A005")]
    used = {(sid, aid) for _, sid, aid in fixed}
    counts = Counter(aid for _, _, aid in fixed)
    result = list(fixed)

    i = 0
    while len(result) < 40 and i < 5000:
        sid = f"S{(i * 3) % 20 + 1:03d}"
        aid = open_ids[(i * 7 + 2) % len(open_ids)]
        i += 1
        if (sid, aid) in used or counts[aid] >= capacities[aid]:
            continue
        used.add((sid, aid))
        counts[aid] += 1
        result.append((f"E{1001 + len(result)}", sid, aid))

    base = datetime(2026, 10, 20, 9, 0)
    rows = []
    for index, (eid, sid, aid) in enumerate(result):
        created = (base + timedelta(minutes=index * 7)).isoformat(timespec="seconds")
        rows.append((eid, sid, aid, "confirmed", created))
    return rows


def seed_database(path: str | Path | None = None) -> Path:
    target = Path(path) if path is not None else DEFAULT_DB
    target.parent.mkdir(parents=True, exist_ok=True)
    schema = (Path(__file__).with_name("schema.sql")).read_text(encoding="utf-8")

    conn = sqlite3.connect(target)
    try:
        conn.executescript(schema)
        conn.executemany(
            "INSERT INTO students VALUES (?, ?, ?, ?, ?, ?)", STUDENTS
        )
        conn.executemany(
            "INSERT INTO courses VALUES (?, ?, ?, ?, ?, ?, ?)", COURSES
        )
        activity_rows = [
            (aid, title, category, date, weekday_of(date), start, end,
             location, capacity, credit, tags, description, organizer, status)
            for (aid, title, category, date, start, end, location,
                 capacity, credit, tags, description, organizer, status) in ACTIVITIES
        ]
        conn.executemany(
            "INSERT INTO activities VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            activity_rows,
        )
        conn.executemany(
            "INSERT INTO enrollments VALUES (?, ?, ?, ?, ?)", build_enrollments()
        )
        conn.executemany(
            "INSERT INTO hours VALUES (?, ?, ?, ?, ?, ?)",
            [(rid, sid, aid, hours, TERM, status) for rid, sid, aid, hours, status in HOURS],
        )
        conn.commit()
    finally:
        conn.close()
    return target


